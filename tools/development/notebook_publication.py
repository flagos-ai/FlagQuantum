"""Publish the native notebook library with explicit section ordering."""

from collections.abc import Callable, Iterable, Sequence
from pathlib import Path

from tools.development.files import WriteIfDifferent
from tools.development.notebook_catalog import notebook_sections
from tools.development.repository import get_git_root

CONCEPTS = (
    "unary_iteration.ipynb",
    "comparison_gate_costs.ipynb",
    "fixed_point_error_analysis.ipynb",
    "quantum_walk_phase_estimation.ipynb",
    "grid_trotter_costs.ipynb",
    "hubbard_qpe_costs.ipynb",
    "register_chemistry_resources.ipynb",
    "chemistry_authoring.ipynb",
    "register_factoring_via_modexp.ipynb",
    "state_preparation_via_rotation_tutorial.ipynb",
    "kikuchi_guiding_state.ipynb",
)
ROOT_COMPONENTS = ("register_elliptic_curve_cryptography.ipynb",)


def all_notebooks(
    sections: Sequence[tuple[str, Sequence[Path]]],
) -> Iterable[Path]:
    for _, notebooks in sections:
        yield from notebooks


def render_notebooks(
    sections: Sequence[tuple[str, Sequence[Path]]],
    render: Callable[[Path], None],
) -> None:
    """Run the existing domain renderer in explicit registration order."""
    for notebook in all_notebooks(sections):
        render(notebook)


def toc_section_lines(
    caption: str, entries: Sequence[str], maxdepth: int = 2
) -> list[str]:
    return (
        [".. toctree::", f"    :maxdepth: {maxdepth}", f"    :caption: {caption}:", ""]
        + [f"    {entry}" for entry in entries]
        + [""]
    )


def write_toc(
    sections: Sequence[tuple[str, Sequence[Path]]],
    source_root: Path,
    destination: Path,
) -> None:
    """Write native library contents with concepts and root components first."""
    lines = [
        ".. _component_library:",
        "",
        "Component Library",
        "=================",
        "",
        "FlagQuantum implements quantum operations and subroutines in native domains.",
        "",
        ".. Note: this file is autogenerated by tools.development.notebook_publication.",
        "",
    ]
    lines += toc_section_lines("Concepts", CONCEPTS, maxdepth=1)
    lines += toc_section_lines("Root Components", ROOT_COMPONENTS, maxdepth=1)
    for section, notebooks in sections:
        entries = [str(path.relative_to(source_root)) for path in notebooks]
        lines += toc_section_lines(section, entries)
    with WriteIfDifferent(destination) as output:
        output.write("\n".join(lines))


def report_unlisted_notebooks(
    sections: Sequence[tuple[str, Sequence[Path]]],
    available: Iterable[Path],
    source_root: Path,
) -> tuple[Path, ...]:
    """Report discovered assets absent from the explicit publication catalog."""
    registered = set(all_notebooks(sections))
    registered.update(source_root / name for name in (*CONCEPTS, *ROOT_COMPONENTS))
    unlisted = tuple(sorted(set(available) - registered))
    if unlisted:
        print("\nWarning: found notebooks outside the publication catalog:")
        for path in unlisted:
            print("   ", str(path.relative_to(source_root)))
    return unlisted


def publish_notebooks(
    source_root: Path,
    destination: Path,
    *,
    sections: Sequence[tuple[str, Sequence[Path]]] | None = None,
    render: Callable[[Path], None] | None = None,
) -> None:
    """Publish authored notebooks, optionally refreshing them through their owner.

    Native notebooks already contain the accepted domain-specific documentation
    and example code. A supplied renderer may regenerate those source assets
    through the existing NotebookSpec renderer before publication. The default
    preserves their exact text. Earlier outputs remain visible if a later
    renderer or copy fails, matching the source's sequential publication.
    """
    selected = notebook_sections(source_root) if sections is None else sections
    if source_root.resolve() == destination.resolve():
        raise ValueError("Notebook publication destination must differ from its source")
    if render is not None:
        render_notebooks(selected, render)
    paths = dict.fromkeys(
        [source_root / name for name in (*CONCEPTS, *ROOT_COMPONENTS)]
        + list(all_notebooks(selected))
    )
    for path in paths:
        relative = path.relative_to(source_root)
        content = path.read_text()
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        with WriteIfDifferent(target) as output:
            output.write(content)
    write_toc(selected, source_root, destination / "index.rst")
    report_unlisted_notebooks(selected, source_root.rglob("*.ipynb"), source_root)


def main() -> None:
    root = get_git_root()
    publish_notebooks(root / "examples/notebooks", root / "docs/components")


if __name__ == "__main__":
    main()
