"""Postprocess generated reference links, metadata and Sphinx contents."""

import re
from collections import defaultdict
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import TextIO

from tools.development.files import WriteIfDifferent


def write_ref_toc(
    output: TextIO | WriteIfDifferent,
    grouped_paths: Mapping[Path, Iterable[Path]],
    output_dir: Path,
) -> None:
    output.write(".. this file is autogenerated\n\n")
    for parent in sorted(grouped_paths, key=lambda path: len(path.parts)):
        output.write(
            "\n".join(
                [".. toctree::", "   :hidden:", f"   :caption: {parent.name}", "", ""]
            )
        )
        for child in sorted(grouped_paths[parent]):
            output.write(f"   {child.relative_to(output_dir)}\n")
        output.write("\n")


def fixup_suffix(content: str) -> str:
    def replace(match: re.Match[str]) -> str:
        before, after = match["before"], match["after"]
        if not after or after[0] not in '#"' or "://" in before:
            return match[0]
        return f"{before}.html{after}"

    return re.sub(
        r"(?<=\s)(?P<before>[\S]+)\.(md|ipynb)(?P<after>[\S]*)", replace, content
    )


def fixup_all_symbols_page(path: Path) -> bool:
    if path.name == "all_symbols.md":
        path.unlink()
        return True
    return False


def remove_extra_files(output_dir: Path, package: str = "flagquantum") -> None:
    for name in ["_toc.yaml", "_redirects.yaml", "_api_cache.json", "api_report.pb"]:
        (output_dir / package / name).unlink(missing_ok=True)


def apply_fixups(reporoot: Path, package: str = "flagquantum") -> None:
    output_dir = reporoot / "docs/reference"
    remove_extra_files(output_dir, package)
    for path in output_dir.glob("**/*.md"):
        if fixup_all_symbols_page(path):
            continue
        content = fixup_suffix(path.read_text())
        with WriteIfDifferent(path) as output:
            output.write(content)


def generate_ref_toc(reporoot: Path, package: str = "flagquantum") -> None:
    output_dir = reporoot / "docs/reference"
    grouped: dict[Path, list[Path]] = defaultdict(list)
    for path in output_dir.glob(f"{package}/**/*.md"):
        grouped[path.parent].append(path)
    with WriteIfDifferent(output_dir / "autotoc.rst.inc") as output:
        write_ref_toc(output, grouped, output_dir)
