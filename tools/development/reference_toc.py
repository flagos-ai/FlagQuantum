from collections.abc import Callable, Sequence
from pathlib import Path

from tools.development.reference_context import RenderContext
from tools.development.reference_links import Writable
from tools.development.reference_pages import ModulePage, Page


def write_toc(
    toc_f: Writable,
    pages: Sequence[Page],
    _page_in_section: Callable[[Page, str], bool],
    _pages_sort_key: Callable[[Page], list[str]],
    render_context: RenderContext,
) -> None:
    toc_f.write(".. this file is autogenerated\n\n")

    for section in render_context.sections:
        if section == "":
            raise ValueError()
        toc_f.write(".. toctree::\n")
        # toc_f.write(f'   :hidden:\n')
        toc_f.write(f"   :caption: {section}\n")
        toc_f.write("   :maxdepth: 2\n\n")

        spages: list[Page] = sorted(
            (p for p in pages if _page_in_section(p, section)), key=_pages_sort_key
        )

        for mp in spages:
            if isinstance(mp, ModulePage) and len(mp.members) == 0:
                print(f"Skipping empty module page {mp.pref_path}")
                continue

            assert mp.pref_path is not None, f"Uninitialized {mp}"
            parts = mp.pref_path.split(".")
            parts[-1] += ".md"
            mp_relpath = render_context.refdoc_relpath / "/".join(parts)
            toc_f.write(f"   /{mp_relpath}\n")

        toc_f.write("\n")


def render_toc(
    out_dir: Path,
    pages: Sequence[Page],
    page_in_section: Callable[[Page, str], bool],
    pages_sort_key: Callable[[Page], list[str]],
    render_context: RenderContext,
) -> None:
    with (out_dir / "autotoc.rst.inc").open("w") as toc_f:
        write_toc(
            toc_f=toc_f,
            pages=pages,
            _page_in_section=page_in_section,
            _pages_sort_key=pages_sort_key,
            render_context=render_context,
        )
