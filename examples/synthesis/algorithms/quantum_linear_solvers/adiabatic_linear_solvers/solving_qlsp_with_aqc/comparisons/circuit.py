def reference_circuit() -> fq.Circuit:
    dtype = torch.complex128
    axes = {
        "I": torch.eye(2, dtype=dtype),
        "X": torch.tensor([[0, 1], [1, 0]], dtype=dtype),
        "Y": torch.tensor([[0, -1j], [1j, 0]], dtype=dtype),
        "Z": torch.diag(torch.tensor([1, -1], dtype=dtype)),
    }
    groups = []
    for table in (H0, H1):
        terms = []
        for word, coefficient in table:
            a, b, c = (axes[axis] for axis in reversed(word))
            terms.append((torch.kron(torch.kron(a, b), c), coefficient))
        groups.append(terms)
    eye = torch.eye(8, dtype=dtype)
    state = torch.tensor(
        [math.sqrt(p / math.fsum(PROBABILITIES)) for p in PROBABILITIES], dtype=dtype
    )
    delta = eye[:, 0] - state
    prepare = eye - 2 * torch.outer(delta, delta.conj()) / delta.vdot(delta)
    circuit = fq.Circuit(3, dtype=dtype).any(0, 1, 2, matrix=prepare)
    for which, time, order, count in SCHEDULE:
        assert order == 1
        product = eye
        for pauli, coefficient in groups[which]:
            angle = time * coefficient / count
            product = (math.cos(angle) * eye - 1j * math.sin(angle) * pauli) @ product
        circuit.any(0, 1, 2, matrix=torch.linalg.matrix_power(product, count))
    return circuit


def run_example() -> None:
    compare_states(build_program(), reference_circuit(), ("qba",))


