def effective_angles(strike: int = 13) -> list[float]:
    """Represent selector >= strike as a finite angle table, without new gates."""
    if type(strike) is not int or not 0 <= strike <= 32:
        raise ValueError("Use an integer strike cutoff in 0..32")
    return [angle if word >= strike else 0.0 for word, angle in enumerate(ANGLE_TABLE)]
