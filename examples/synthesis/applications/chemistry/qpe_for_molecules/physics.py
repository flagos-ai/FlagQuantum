def commute(left: Term, right: Term) -> bool:
    return sum(a != b for i, a in left[0] for j, b in right[0] if i == j) % 2 == 0


def commuting_runs(terms: tuple[Term, ...]) -> tuple[tuple[Term, ...], ...]:
    groups: list[list[Term]] = []
    for term in terms:
        if not groups or not all(commute(term, previous) for previous in groups[-1]):
            groups.append([])
        groups[-1].append(term)
    return tuple(tuple(group) for group in groups)


def observable(terms: tuple[Term, ...]) -> fq.Observable:
    products = []
    for support, coefficient in terms:
        product = fq.I()
        for bit, axis in support:
            factor = {"X": fq.X, "Y": fq.Y, "Z": fq.Z}[axis](bit)
            product = product @ factor
        products.append(coefficient * product)
    total = products[0]
    for product in products[1:]:
        total = total + product
    return total


