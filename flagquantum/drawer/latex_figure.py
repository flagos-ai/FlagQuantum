"""Portable LaTeX figures and bounded, optional Notebook rendering."""

from __future__ import annotations

import math
import shutil
import subprocess
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from importlib.resources import files
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import Literal

ImageFormat = Literal["pdf", "svg", "png"]


def _document(body: str) -> str:
    return (
        "\\documentclass[border=12pt]{standalone}\n"
        "\\usepackage{flaghybrid}\n\\begin{document}\n" + body + "\\end{document}\n"
    )


def _runtime_files() -> dict[str, bytes]:
    root = files("flagquantum.drawer").joinpath("tex")
    result = {
        p.name: p.read_bytes()
        for p in root.iterdir()
        if p.is_file() and p.name.endswith((".sty", ".tex", ".md"))
    }
    result.update(
        {
            "licenses/" + p.name: p.read_bytes()
            for p in root.joinpath("licenses").iterdir()
            if p.is_file()
        }
    )
    return result


def _write_runtime(directory: Path) -> None:
    for name, data in _runtime_files().items():
        target = directory / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def _tool(name: str, purpose: str) -> str:
    executable = shutil.which(name)
    if executable is None:
        raise ImportError(
            f"{purpose} requires {name!r} on PATH. Install Tectonic or TeX Live "
            "for PDF compilation and Poppler for SVG/PNG conversion. "
            "LaTeX source export needs neither; use figure.source or figure.export_bundle(path)."
        )
    return executable


def _run(command: Sequence[str], directory: Path, timeout: float) -> None:
    # Compiler logs can be large; retain them on the temporary build's disk,
    # then read only the tail needed for an actionable failure.
    with (directory / "render-output.log").open("w+b") as log:
        try:
            subprocess.run(
                command,
                cwd=directory,
                timeout=timeout,
                check=True,
                stdout=log,
                stderr=subprocess.STDOUT,
                text=True,
                errors="replace",
            )
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError(
                f"LaTeX rendering timed out after {timeout:g}s: {command[0]}"
            ) from exc
        except subprocess.CalledProcessError as exc:
            log.seek(0, 2)
            log.seek(max(0, log.tell() - 6000))
            diagnostic = log.read().decode("utf-8", errors="replace")
            if exc.stdout:
                diagnostic = str(exc.stdout)[-6000:]
            raise RuntimeError(
                f"LaTeX rendering failed in {command[0]}:\n{diagnostic}"
            ) from exc
        except OSError as exc:
            raise RuntimeError(
                f"Cannot run rendering tool {command[0]}: {exc}"
            ) from exc


@dataclass(frozen=True)
class LatexFigure:
    """Editable source with lazy rendering and rich Notebook display.

    Source export never starts a compiler. Rendering needs a local TeX engine;
    Notebook image display additionally needs Poppler. Cache ownership is local
    to this immutable figure, with no shared disk cache.

    Args:
        source: LaTeX generated by the drawer, or caller-trusted source.
        standalone: Whether source already contains a complete document.
        engine: Executable name/path for Tectonic or a supported TeX Live engine.
        timeout: Maximum seconds per compiler or converter invocation.

    Examples:
        >>> import flagquantum as fq
        >>> figure = fq.Circuit(2).h(0).cx(0, 1).draw(format="latex")
        >>> "\\\\begin{yquant}" in figure.source
        True
    """

    source: str
    standalone: bool = True
    engine: str | None = None
    timeout: float = 120.0
    _cache: dict[str, bytes] = field(
        default_factory=dict, init=False, repr=False, compare=False
    )

    def __post_init__(self) -> None:
        if not isinstance(self.source, str):
            raise TypeError("source must be a string")
        if not isinstance(self.standalone, bool):
            raise TypeError("standalone must be a bool")
        if self.engine is not None and not isinstance(self.engine, str):
            raise TypeError("engine must be an executable name or path")
        if (
            isinstance(self.timeout, bool)
            or not math.isfinite(self.timeout)
            or self.timeout <= 0
        ):
            raise ValueError("timeout must be finite and positive")

    def __str__(self) -> str:
        return self.source

    def __repr__(self) -> str:
        return f"LatexFigure({len(self.source)} source characters; use .source or .render())"

    def save_source(self, path: str | Path) -> Path:
        """Write editable source without compiling; return the output path."""
        target = Path(path)
        target.write_text(self.source, encoding="utf-8")
        return target

    def export_bundle(self, directory: str | Path) -> Path:
        """Write a standalone figure.tex, runtime files and all component licenses.

        Existing files with different contents raise FileExistsError before any
        file is written. The result can be uploaded directly to Overleaf.
        """
        root = Path(directory)
        assets = _runtime_files()
        assets["figure.tex"] = self._document_source().encode("utf-8")
        for name, data in assets.items():
            target = root / name
            if any(
                parent.exists() and not parent.is_dir() for parent in target.parents
            ):
                raise FileExistsError(f"Bundle path contains a non-directory: {target}")
            if target.exists() and (
                not target.is_file() or target.read_bytes() != data
            ):
                raise FileExistsError(f"Refusing to overwrite bundle file: {target}")
        for name, data in assets.items():
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        return root / "figure.tex"

    def _document_source(self) -> str:
        return self.source if self.standalone else _document(self.source)

    def _compile_pdf(self) -> bytes:
        engine = self.engine
        if engine is None:
            engine = next(
                (
                    name
                    for name in ("tectonic", "pdflatex", "xelatex", "lualatex")
                    if shutil.which(name)
                ),
                "tectonic",
            )
        executable = _tool(engine, "LaTeX compilation")
        name = Path(executable).stem.lower()
        if name not in ("tectonic", "pdflatex", "xelatex", "lualatex"):
            raise ValueError("engine must be Tectonic, pdfLaTeX, XeLaTeX or LuaLaTeX")
        with TemporaryDirectory(prefix="flagquantum-latex-") as temporary:
            root = Path(temporary)
            _write_runtime(root)
            (root / "figure.tex").write_text(self._document_source(), encoding="utf-8")
            arguments = (
                ["--untrusted", "figure.tex"]
                if name == "tectonic"
                else [
                    "-no-shell-escape",
                    "-interaction=nonstopmode",
                    "-halt-on-error",
                    "figure.tex",
                ]
            )
            _run([executable, *arguments], root, self.timeout)
            output = root / "figure.pdf"
            if not output.is_file():
                raise RuntimeError("TeX engine completed without producing figure.pdf")
            data = output.read_bytes()
            if not data.startswith(b"%PDF-"):
                raise RuntimeError("TeX engine did not produce a valid PDF header")
            return data

    def render(self, format: ImageFormat = "pdf") -> bytes:
        """Compile/convert to bytes, reusing this figure's previous results.

        SVG needs pdftocairo. PNG needs pdftoppm or pdftocairo. Compilation and
        conversion failures raise RuntimeError; missing tools raise ImportError.
        """
        if format not in ("pdf", "svg", "png"):
            raise ValueError("render format must be 'pdf', 'svg' or 'png'")
        if format in self._cache:
            return self._cache[format]
        converter: str | None = None
        if format == "svg":
            converter = _tool("pdftocairo", "SVG conversion")
        elif format == "png":
            converter = _tool(
                "pdftoppm" if shutil.which("pdftoppm") else "pdftocairo",
                "PNG conversion",
            )
        if "pdf" not in self._cache:
            self._cache["pdf"] = self._compile_pdf()
        if format == "pdf":
            return self._cache["pdf"]
        assert converter is not None
        with TemporaryDirectory(prefix="flagquantum-image-") as temporary:
            root = Path(temporary)
            (root / "figure.pdf").write_bytes(self._cache["pdf"])
            arguments = (
                ["-svg", "figure.pdf", "figure.svg"]
                if format == "svg"
                else ["-png", "-singlefile", "-r", "160", "figure.pdf", "figure"]
            )
            _run([converter, *arguments], root, self.timeout)
            target = root / ("figure." + format)
            if not target.is_file():
                raise RuntimeError(
                    f"Converter completed without producing {target.name}"
                )
            data = target.read_bytes()
            if format == "png" and not data.startswith(b"\x89PNG\r\n\x1a\n"):
                raise RuntimeError("Converter did not produce a valid PNG header")
            if format == "svg" and "<svg" not in data.decode("utf-8"):
                raise RuntimeError("Converter did not produce an SVG document")
            self._cache[format] = data
            return data

    def save(self, path: str | Path) -> Path:
        """Save .tex source or a compiled .pdf/.svg/.png figure."""
        target = Path(path)
        suffix = target.suffix.lower()
        if suffix == ".tex":
            return self.save_source(target)
        formats: dict[str, ImageFormat] = {".pdf": "pdf", ".svg": "svg", ".png": "png"}
        if suffix not in formats:
            raise ValueError("output extension must be .tex, .pdf, .svg or .png")
        target.write_bytes(self.render(formats[suffix]))
        return target

    def display(self) -> None:
        """Display inline using IPython, importing it only when requested."""
        from IPython.display import display

        show_figure: Callable[[object], None] = display
        show_figure(self)

    def _repr_mimebundle_(
        self,
        include: Sequence[str] | None = None,
        exclude: Sequence[str] | None = None,
    ) -> dict[str, str | bytes]:
        allowed = {"text/plain", "image/svg+xml", "image/png"}
        if include is not None:
            allowed.intersection_update(include)
        if exclude is not None:
            allowed.difference_update(exclude)
        result: dict[str, str | bytes] = {}
        if "text/plain" in allowed:
            result["text/plain"] = repr(self)
        if "image/svg+xml" in allowed and (
            shutil.which("pdftocairo") or "image/png" not in allowed
        ):
            result["image/svg+xml"] = self.render("svg").decode("utf-8")
        elif "image/png" in allowed:
            result["image/png"] = self.render("png")
        return result
